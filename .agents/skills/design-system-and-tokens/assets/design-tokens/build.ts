// Builds dist/tokens.css from tokens/*.json and fails when a contrast pair misses its WCAG minimum.
// Usage: node build.ts            write dist/tokens.css and report contrast
//        node build.ts --check    report only; exit 1 on any failure (for CI)

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  type ContrastPair,
  type ContrastResult,
  checkContrast,
  cssDeclarations,
  type FlatToken,
  flattenTokens,
  mergeTokenSets,
} from "./tokens.ts";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const THEMES = ["light", "dark"] as const;
type Theme = (typeof THEMES)[number];

async function readJson(relativePath: string): Promise<unknown> {
  return JSON.parse(await readFile(path.join(ROOT, relativePath), "utf8"));
}

function parsePairs(raw: unknown): ContrastPair[] {
  const pairs = typeof raw === "object" && raw !== null && "pairs" in raw ? raw.pairs : undefined;
  if (!Array.isArray(pairs)) throw new Error('contrast-pairs.json: expected a "pairs" array');
  return pairs.map((pair: unknown, index) => {
    if (typeof pair !== "object" || pair === null) throw new Error(`contrast pair ${index}: expected an object`);
    const { foreground, background, minimum }: { foreground?: unknown; background?: unknown; minimum?: unknown } = pair;
    if (typeof foreground !== "string" || typeof background !== "string" || typeof minimum !== "number") {
      throw new Error(`contrast pair ${index}: needs foreground, background (strings) and minimum (number)`);
    }
    return { foreground, background, minimum };
  });
}

/** Every theme must define exactly the same semantic token paths, or components break in one theme. */
function assertSameShape(themes: Record<Theme, FlatToken[]>): void {
  const [first, ...rest] = THEMES;
  const expected = themes[first]
    .map((token) => token.path)
    .sort()
    .join("\n");
  for (const theme of rest) {
    if (
      themes[theme]
        .map((token) => token.path)
        .sort()
        .join("\n") !== expected
    ) {
      throw new Error(`theme "${theme}" does not define the same tokens as "${first}"`);
    }
  }
}

export interface BuildResult {
  readonly css: string;
  readonly contrast: Record<Theme, ContrastResult[]>;
}

export async function build(): Promise<BuildResult> {
  const base = flattenTokens(await readJson("tokens/base.json"));
  const themes = {
    light: flattenTokens(await readJson("tokens/light.json")),
    dark: flattenTokens(await readJson("tokens/dark.json")),
  };
  assertSameShape(themes);
  const pairs = parsePairs(await readJson("contrast-pairs.json"));
  const light = mergeTokenSets(base, themes.light);
  const dark = mergeTokenSets(base, themes.dark);
  const isTheme = (tokenPath: string): boolean => tokenPath.startsWith("theme.");
  const indent = (lines: string[], depth: number): string =>
    lines.map((line) => `${"  ".repeat(depth)}${line}`).join("\n");

  // Light is the default. Dark follows the OS setting unless the page forces a theme with data-theme.
  const css = `/* Generated by build.ts from tokens/*.json. Do not edit by hand. */
:root {
${indent(
  cssDeclarations(light, (tokenPath) => !isTheme(tokenPath)),
  1,
)}
${indent(cssDeclarations(light, isTheme), 1)}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${indent(cssDeclarations(dark, isTheme), 2)}
    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${indent(cssDeclarations(dark, isTheme), 1)}
  color-scheme: dark;
}
`;
  return { css, contrast: { light: checkContrast(light, pairs), dark: checkContrast(dark, pairs) } };
}

async function main(): Promise<void> {
  const checkOnly = process.argv.includes("--check");
  const { css, contrast } = await build();
  let failures = 0;
  for (const theme of THEMES) {
    for (const result of contrast[theme]) {
      const status = result.passes ? "pass" : "FAIL";
      if (!result.passes) failures += 1;
      console.log(
        `${status} ${theme.padEnd(5)} ${result.ratio.toFixed(2).padStart(5)}:1 (min ${result.minimum}) ${result.foreground} on ${result.background}`,
      );
    }
  }
  if (!checkOnly) {
    await mkdir(path.join(ROOT, "dist"), { recursive: true });
    await writeFile(path.join(ROOT, "dist", "tokens.css"), css);
    console.log("wrote dist/tokens.css");
  }
  console.log(`${failures} contrast failure(s)`);
  process.exitCode = failures > 0 ? 1 : 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
